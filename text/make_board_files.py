"""W5 task 1: write the board text-embedding files (format MCTX v1) from results/text_vocab_<mode>.npy.

usage: make_board_files.py <templates80|simple>
Writes board_files/demo_text.bin, board_files/demo_text.txt, board_files/demo_text.py (python data module) and
results/board_text_check.json (int8 vs FP32 text: per-row cosine, and a parse-back check).

FORMAT demo_text.bin (all little endian):
  off  size  field
  0    4     magic b"MCTX"
  4    2     uint16 version = 1
  6    2     uint16 N  (number of entries)
  8    2     uint16 D  (= 512)
  10   2     uint16 prompt mode: 0 = 80 OpenAI ImageNet templates (ensembled), 1 = "a photo of a {name}."
  12   4     uint32 CRC32 (zlib / binascii.crc32) of bytes [16 : 16 + 4N + N*D]
  16   4N    float32 row scale s_i
  16+4N N*D  int8 q_i,k, row-major (entry i at 16 + 4N + i*D)
  t_i,k (FP32, L2-normalized) ~= s_i * q_i,k with s_i = max_k |t_i,k| / 127, q = round(t / s_i) (half to even).
  For cosine scoring the row scale cancels: cos_i = (q_i . v) / (|q_i| |v|), v = board output int8 - output zp.
demo_text.txt: the N display names, one per line ("\\n"), same order as the rows, ASCII.
demo_text.py : NAMES (list), MODE (str), BIN_B64 (base64 of demo_text.bin) -> board: import demo_text."""
import sys, json, base64, zlib, struct, pathlib, hashlib
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import common, vocab  # noqa: E402

MODES = {"templates80": 0, "simple": 1}


def quantize_rows(T):
    s = np.abs(T).max(1) / 127.0
    q = np.clip(np.rint(T / s[:, None]), -127, 127).astype(np.int8)
    return s.astype(np.float32), q


def pack(T, mode):
    n, d = T.shape
    s, q = quantize_rows(T.astype(np.float64))
    body = s.astype("<f4").tobytes() + q.tobytes()
    head = b"MCTX" + struct.pack("<HHHHI", 1, n, d, MODES[mode], zlib.crc32(body) & 0xFFFFFFFF)
    return head + body, s, q


def parse(b):
    """PC parser (mirror of the board loader)."""
    assert b[:4] == b"MCTX"
    ver, n, d, mode, crc = struct.unpack("<HHHHI", b[4:16])
    assert ver == 1 and zlib.crc32(b[16:]) & 0xFFFFFFFF == crc and len(b) == 16 + 4 * n + n * d
    s = np.frombuffer(b, "<f4", n, 16)
    q = np.frombuffer(b, np.int8, n * d, 16 + 4 * n).reshape(n, d)
    return {"version": ver, "n": n, "d": d, "mode": mode, "crc": crc, "scales": s, "q": q}


def main(mode):
    T = np.load(common.RES / f"text_vocab_{mode}.npy").astype(np.float32)
    names = vocab.display_names()
    assert len(names) == len(T)
    b, s, q = pack(T, mode)
    out = common.H / "board_files"; out.mkdir(exist_ok=True)
    (out / "demo_text.bin").write_bytes(b)
    (out / "demo_text.txt").write_bytes(("\n".join(names) + "\n").encode("ascii"))
    b64 = base64.b64encode(b).decode()
    mod = ('# Generated by night/W5_demo/pc/make_board_files.py (W5 demo text embeddings, format MCTX v1, see README).\n'
           f'MODE = "{mode}"\nNAMES = {names!r}\n'
           'BIN_B64 = (\n' + "".join(f'    "{b64[i:i + 100]}"\n' for i in range(0, len(b64), 100)) + ')\n')
    (out / "demo_text.py").write_text(mod, newline="\n")
    p = parse(b)
    deq = p["q"].astype(np.float64) * p["scales"][:, None].astype(np.float64)
    cos = (deq * T).sum(1) / np.linalg.norm(deq, axis=1) / np.linalg.norm(T, axis=1)
    chk = {"mode": mode, "n": int(p["n"]), "bytes": len(b), "crc32": "0x%08x" % p["crc"],
           "sha256": {f: hashlib.sha256((out / f).read_bytes()).hexdigest() for f in ("demo_text.bin", "demo_text.txt", "demo_text.py")},
           "int8_vs_fp32_row_cos_min": float(cos.min()), "int8_vs_fp32_row_cos_mean": float(cos.mean()),
           "parse_back_q_equal": bool(np.array_equal(p["q"], q))}
    json.dump(chk, open(common.RES / "board_text_check.json", "w"), indent=1)
    print(json.dumps(chk, indent=1))
    return b, names


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "templates80")

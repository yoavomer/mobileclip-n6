"""Overnight 2 (9.11 -> 10.11): build the v2 board scripts into release/v2/board/.
Nothing of the working demo is changed: the known-good scripts under night/demo_run/board/ are only READ.
From them this script takes, byte for byte: the configuration block, the 43-word text data, the known-answer data
(ka_demo.py) and the overlay() function. core.py in src/ is a byte-identical copy of night/demo_run/board_src/core.py.
usage: python -I make_v2.py [name ...]     (no name = all)"""
import os  # MCLIP_ROOT = the working folder (default: current folder)
import sys, hashlib, pathlib, json

R = pathlib.Path(os.environ.get("MCLIP_ROOT", ".") + r""); KG = R / "night" / "demo_run" / "board"; V2 = R / "release" / "v2"
SRC = V2 / "src"; OUT = V2 / "board"
MARK = "# ---------------------------------------------------------------- "


def cut(s, a, b):
    i = s.index(a); j = s.index(b, i + len(a))
    return s[i:j]


def parts():
    demo = (KG / "demo.py").read_text()
    assert hashlib.sha256((KG / "demo.py").read_bytes()).hexdigest().startswith("447b90b2c3231213"), "demo.py changed"
    ka = (KG / "ka_demo.py").read_text()
    core = (SRC / "core.py").read_text()
    assert core == (R / "night/demo_run/board_src/core.py").read_text()
    assert cut(demo, MARK + "core", MARK + "demo main loop").rstrip("\n") == core.rstrip("\n"), "core differs from demo.py"
    return {
        "config": cut(demo, MARK + "configuration", MARK + "core"),
        "core": core,
        "overlay": cut(demo, "def overlay(img, names, top, fps):", "def main():"),
        "text": cut(demo, MARK + "embedded text data", "\nmain()\n"),
        "ka": cut(ka, MARK + "known-answer data", "\nmain()\n"),
    }


def litframe():
    """The lit VGA camera frame of 9.11 and the known-good CRCs of its 15 crops, from the known-good crops log."""
    import base64, binascii, re
    log = (R / "night/demo_run/logs/s5b_crops_run2.txt").read_text()
    fb = bytearray(); exp = []
    for ln in log.splitlines():
        if ln.startswith("F "):
            _, off, b = ln.split()
            assert int(off) == len(fb), ln[:20]
            fb += base64.b64decode(b)
        m = re.match(r"CR (\w+) (\w+) box=(\d+),(\d+),(\d+),(\d+) in=(0x[0-9a-f]{8}),(0x[0-9a-f]{8}),(0x[0-9a-f]{8}) "
                     r"out=(0x[0-9a-f]{8}),(0x[0-9a-f]{8}),(0x[0-9a-f]{8}) SAME", ln)
        if m:
            g = m.groups()
            assert g[6] == g[7] == g[8] and g[9] == g[10] == g[11]
            box = None if (g[0], g[1]) == ("full", "centre") else tuple(int(x) for x in g[2:6])
            exp.append((g[0], g[1], box, g[6], g[9]))
    assert len(fb) == 512000 and binascii.crc32(fb) & 0xFFFFFFFF == 0x3ee383b5 and len(exp) == 15, (len(fb), len(exp))
    c = MARK + "known-good crop boxes and CRCs (night/demo_run/logs/s5b_crops_run2.txt, 9.11)\n"
    c += "FRAME_W = 640\nFRAME_H = 400\nFRAME_CRC = 0x3ee383b5\n"
    c += "CROPS_EXP = [   # (name, variant, box or None = centre square, input crc, output crc)\n"
    for e in exp:
        c += "    (%r, %r, %r, %s, %s),\n" % e
    c += "]\n"
    f = MARK + "stored lit VGA frame of 9.11 (RGB565, 512000 bytes, crc 0x3ee383b5), base64 in parts\n"
    f += "FRAME_PARTS = [\n"
    for o in range(0, len(fb), 48000):
        f += '"%s",\n' % base64.b64encode(bytes(fb[o:o + 48000])).decode()
    f += "]\n"
    return c, f


HEAD = '''import machine
wdt = machine.WDT(timeout=10000)
# {title}
# Generated by release/v2/make_v2.py (overnight 2). The known-good demo files are not touched.
# OpenMV N6, firmware 5.0.1. Model mci0_256_w3u_splitdw4 (ROMFS 0x70f2b1c0). WDT 10 s first; fed in every loop and
# around every predict. Nothing is written to the board's drive.
import time, gc, uctypes, binascii, struct, math, image, csi, ml

'''

V2SRC = ["v2_lib.py", "demo_v2_main.py"]
# name -> (title, [source files in src/], [data blocks], edits applied to the configuration block + the source files)
JOBS = {
    "cap_emb.py": ("Run A: known-good loop + stage timers + 300 stored outputs + benchmarks",
                   ["OVERLAY", "cap_emb_main.py"], ["text"], {}),
    "demo_v2.py": ("Demo v2: smoothing + '?' when unsure + faster loop (the model and its input bytes are unchanged)",
                   V2SRC, ["text"], {}),
    "demo_v2_meas.py": ("Demo v2, measurement build: 400 frames, resize timer on",
                        V2SRC, ["text"], {"MAX_FRAMES = 0 ": "MAX_FRAMES = 400 ", "PROFILE = 0 ": "PROFILE = 1 "}),
    "v2_switch.py": ("v2 stored-frame test: byte check of every crop + crop-switch latency",
                     ["v2_lib.py", "v2_switch_main.py"], ["text", "cropsexp", "litframe"], {}),
    "v2_switch_live.py": ("v2 crop-switch latency on live VGA frames",
                          ["v2_lib.py", "v2_switch_main.py"], ["text", "cropsexp"],
                          {'SW_SOURCE = "stored"': 'SW_SOURCE = "live"', "FRAMESIZE = csi.QVGA": "FRAMESIZE = csi.VGA"}),
}


def build(names=None):
    P = parts(); OUT.mkdir(exist_ok=True); res = {}
    for name, (title, srcs, data, edits) in JOBS.items():
        if names and name not in names:
            continue
        if ("cropsexp" in data or "litframe" in data) and "cropsexp" not in P:
            P["cropsexp"], P["litframe"] = litframe()
        body = P["config"] + "@@CORE@@"
        for f in srcs:
            body += (P["overlay"] if f == "OVERLAY" else (SRC / f).read_text()) + "\n\n"
        for a, b in edits.items():
            assert body.count(a) == 1, (a, body.count(a))
            body = body.replace(a, b)
        s = HEAD.format(title=title) + body.replace("@@CORE@@", P["core"] + "\n\n")
        for d in data:
            s += ("\n" if not P[d].startswith("\n") else "") + P[d] + "\n"
        s += "\nmain()\n"
        compile(s, name, "exec")
        assert P["core"] in s
        (OUT / name).write_text(s, newline="\n")
        res[name] = {"bytes": len(s.encode()), "sha256": hashlib.sha256(s.encode()).hexdigest()}
        print(name, res[name]["bytes"], res[name]["sha256"][:16])
    return res


if __name__ == "__main__":
    build(sys.argv[1:] or None)

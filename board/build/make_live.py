"""Overnight 2, Part 5: builds the live-word board scripts into release/live/board/.
Re-uses the v2 builder's pieces (release/v2/make_v2.py is imported, not modified): the known-good configuration block,
the byte-identical known-good core, the 43 demo words, the stored lit frame, and v2_lib.py (smoothing, "?").
usage: python -I make_live.py [script name ...]"""
import os  # MCLIP_ROOT = the working folder (default: current folder)
import sys, re, hashlib, pathlib

sys.path.insert(0, os.environ.get("MCLIP_ROOT", ".") + "/release/v2")
import make_v2 as MV  # noqa: E402

LIVE = MV.R / "release" / "live"
SRC = LIVE / "src"; OUT = LIVE / "board"

HEAD = '''import machine
wdt = machine.WDT(timeout=10000)
# {title}
# Generated by release/live/make_live.py (overnight 2, Part 5). The known-good demo files are not touched.
# OpenMV N6, firmware 5.0.1. Model mci0_256_w3u_splitdw4 (ROMFS 0x70f2b1c0). WDT 10 s first; fed in every loop and
# around every predict. The board only READS /flash/liveword.bin; nothing is written to the board's drive.
import time, gc, uctypes, binascii, struct, math, image, csi, ml

'''

# name -> (title, [source files: "v2:" = release/v2/src, else release/live/src], [data blocks], edits)
JOBS = {
    "live_crops.py": ("Live word proof: a word typed on the PC is scored on 8 crops of the stored lit frame",
                      ["v2:v2_lib.py", "live_lib.py", "live_crops_main.py"], ["text", "cropsexp", "litframe"], {}),
    "live_demo.py": ("Live word demo: camera, v2 top-3 + the word typed on the PC (runs until stopped)",
                     ["v2:v2_lib.py", "live_lib.py", "live_demo_main.py"], ["text"], {}),
    "live_demo_meas.py": ("Live word demo, measurement build: 660 frames (about 2 minutes)",
                          ["v2:v2_lib.py", "live_lib.py", "live_demo_main.py"], ["text"],
                          {"LIVE_FRAMES = 0 ": "LIVE_FRAMES = 660 "}),
}


def build(names=None):
    P = MV.parts(); OUT.mkdir(exist_ok=True); res = {}
    for name, (title, srcs, data, edits) in JOBS.items():
        if names and name not in names:
            continue
        if ("cropsexp" in data or "litframe" in data) and "cropsexp" not in P:
            P["cropsexp"], P["litframe"] = MV.litframe()
        body = P["config"] + "@@CORE@@"
        for f in srcs:
            body += ((MV.SRC / f[3:]) if f.startswith("v2:") else (SRC / f)).read_text() + "\n\n"
        for a, b in edits.items():
            assert body.count(a) == 1, (a, body.count(a))
            body = body.replace(a, b)
        s = HEAD.format(title=title) + body.replace("@@CORE@@", P["core"] + "\n\n")
        for d in data:
            s += ("\n" if not P[d].startswith("\n") else "") + P[d] + "\n"
        s += "\nmain()\n"
        compile(s, name, "exec")
        assert P["core"] in s and "open(LW_PATH, \"rb\")" in s
        # every open() in the script is a READ (known-good core: /rom files; live_lib: the live word file)
        modes = re.findall(r'open\([^()]*?,\s*"([^"]*)"\)', s)
        assert len(modes) >= 4 and all(mo in ("r", "rb") for mo in modes), modes
        assert ".write(" not in s and "os.remove" not in s and "os.rename" not in s
        (OUT / name).write_text(s, newline="\n")
        res[name] = {"bytes": len(s.encode()), "sha256": hashlib.sha256(s.encode()).hexdigest()}
        print(name, res[name]["bytes"], res[name]["sha256"][:16])
    return res


if __name__ == "__main__":
    build(sys.argv[1:] or None)
